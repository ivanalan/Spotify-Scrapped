export function themeFor(
  direction: StoryboardDirectionId,
  slideIndex: number,
): SlideTheme {
  const table =
    direction === "cascade-rings"
      ? CASCADE
      : direction === "dot-orbit"
        ? DOT
        : QUARTER;
  return table[slideIndex] ?? table[0];
}
